"""Volcado y carga de datos para cambiar de motor. / Data dump and load to change engine.

Es el procedimiento de la guía de `docs/`: `dumpdata` en el motor actual y `loaddata` en
una base de datos vacía. Los tipos de contenido y los permisos se regeneran solos, así que
no se exportan.

This is the procedure from the `docs/` guide: `dumpdata` on the current engine and
`loaddata` into an empty database. Content types and permissions are regenerated by
Django, so they are not exported.
"""

from pathlib import Path

import pytest
from django.contrib.auth import get_user_model
from django.core.management import call_command


@pytest.mark.django_db(transaction=True)
def test_dumpdata_y_loaddata_conservan_los_datos(tmp_path: Path) -> None:
    """Un volcado restaurado en una base vacía devuelve los mismos datos.

    A dump restored into an empty database returns the same data.
    """
    user_model = get_user_model()
    user_model.objects.create_user(username="ana", password="una-contraseña-larga-123")
    fichero = tmp_path / "datos.json"

    call_command(
        "dumpdata",
        exclude=["contenttypes", "auth.permission"],
        output=str(fichero),
        verbosity=0,
    )
    call_command("flush", interactive=False, inhibit_post_migrate=True, verbosity=0)
    assert user_model.objects.count() == 0

    call_command("loaddata", str(fichero), verbosity=0)

    assert list(user_model.objects.values_list("username", flat=True)) == ["ana"]
